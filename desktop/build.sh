#!/usr/bin/env bash
# Build the VXVisor Console desktop client for Linux and Windows using
# fyne-cross (Docker). Produces raw, ready-to-run binaries under ./staging,
# named by platform, suitable for dropping into a server's clients/ folder.
#
# Usage: ./build.sh [version]   e.g. ./build.sh v1.0.0
set -euo pipefail
cd "$(dirname "$0")"

VERSION="${1:-dev-$(date +%Y%m%d)}"
export PATH="$PATH:$(go env GOPATH)/bin"

if ! command -v fyne-cross >/dev/null 2>&1; then
  echo "fyne-cross not found; installing..."
  go install github.com/fyne-io/fyne-cross@latest
fi

APP=com.vxvisor.console

# fyne-cross's -ldflags is forwarded to the C/external linker, not `go build`,
# so Go's `-X` does not apply. Bake the version as a generated Go literal instead
# (removed again when the build finishes, success or fail).
GEN=internal/ui/version_gen.go
cleanup(){ rm -f "$GEN"; }
trap cleanup EXIT
cat > "$GEN" <<EOF
// Code generated by build.sh. DO NOT EDIT.
package ui

func init() { Version = "${VERSION}" }
EOF

echo ">> Building linux/amd64 ..."
fyne-cross linux   -arch=amd64 -app-id "$APP" -icon Icon.png -name vxconsole ./cmd/vxconsole

echo ">> Building windows/amd64 ..."
fyne-cross windows -arch=amd64 -app-id "$APP" -icon Icon.png -name vxconsole ./cmd/vxconsole

mkdir -p staging
# fyne-cross leaves the raw compiled binary under fyne-cross/bin/<os>-<arch>/.
cp fyne-cross/bin/linux-amd64/vxconsole       "staging/vxconsole-${VERSION}-linux-amd64"
cp fyne-cross/bin/windows-amd64/vxconsole.exe "staging/vxconsole-${VERSION}-windows-amd64.exe"

echo
echo "Done. Artifacts:"
ls -lh staging/
echo
echo "To publish on a server's download page, copy these into its data dir:"
echo "  scp staging/vxconsole-* HOST:/tmp/ && ssh HOST 'sudo mkdir -p /var/lib/vdxclone/data/clients && sudo mv /tmp/vxconsole-* /var/lib/vdxclone/data/clients/'"
